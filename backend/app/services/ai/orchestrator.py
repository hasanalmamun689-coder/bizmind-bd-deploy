"""
section 24: the AI assistant's answer must always contain Answer, Evidence,
Reasoning and Suggested action, and the evidence must come from real tool
calls — never invented. This module is the only place that assembles those
four pieces before they reach the API layer.
"""
import uuid

from sqlalchemy.orm import Session

from app.models.ai import AgentRun, AIConversation, AIMessage
from app.services.ai.provider import NullProvider, get_provider
from app.services.ai.tools import TOOL_REGISTRY, TOOL_SPECS

SYSTEM_PROMPT = (
    "You are the BizMind BD business assistant. You may only use the "
    "provided tools to look up real business data — never invent numbers. "
    "Always structure your final answer with a concise Answer, the specific "
    "Evidence you used, your Reasoning, and a Suggested action. If a tool "
    "reports insufficient data, say so plainly instead of guessing."
)

MAX_TOOL_ROUNDS = 3


def _run_tools(db: Session, business_id: uuid.UUID, tool_calls) -> list[dict]:
    results = []
    for call in tool_calls:
        fn = TOOL_REGISTRY.get(call.name)
        if fn is None:
            results.append({"tool": call.name, "error": "unknown tool"})
            continue
        try:
            output = fn(db, business_id, **call.arguments)
        except TypeError:
            # Arguments didn't match the tool's signature — call with no args
            # rather than fail the whole request.
            output = fn(db, business_id)
        except Exception as exc:  # noqa: BLE001
            output = {"error": str(exc)}
        results.append({"tool": call.name, "result": output})
    return results


def _format_deterministic_answer(tool_results: list[dict]) -> tuple[str, str | None]:
    """Turn raw tool JSON into a plain-language answer with no invented facts."""
    answer = (
        "Here is what the current business data shows for your question — "
        "see the evidence for the exact figures behind it."
    )
    suggested_action = None
    for entry in tool_results:
        result = entry.get("result")
        if isinstance(result, dict) and result.get("low_stock_products"):
            suggested_action = "Review the listed low-stock products and consider a purchase order."
            break
        if isinstance(result, dict) and result.get("risks"):
            risky = [r for r in result["risks"] if r.get("severity") != "info"]
            if risky:
                suggested_action = f"Investigate: {risky[0]['risk']}."
                break
    return answer, suggested_action


def chat(
    db: Session,
    business_id: uuid.UUID,
    user_id: uuid.UUID,
    conversation_id: uuid.UUID | None,
    message: str,
) -> dict:
    conversation = None
    if conversation_id:
        conversation = db.get(AIConversation, conversation_id)
        if conversation is not None and conversation.business_id != business_id:
            conversation = None
    if conversation is None:
        conversation = AIConversation(business_id=business_id, user_id=user_id, title=message[:80])
        db.add(conversation)
        db.flush()

    db.add(AIMessage(conversation_id=conversation.id, role="user", content=message))

    live_provider = get_provider()
    used_live_model = live_provider is not None
    provider = live_provider or NullProvider()

    history = [{"role": "user", "content": message}]
    all_tool_results: list[dict] = []
    final_text: str | None = None

    for _ in range(MAX_TOOL_ROUNDS):
        step = provider.next_step(SYSTEM_PROMPT, history, TOOL_SPECS, all_tool_results)
        if step.tool_calls:
            all_tool_results.extend(_run_tools(db, business_id, step.tool_calls))
            continue
        final_text = step.final_text
        break

    # Safety net: if a live provider never called a tool and never returned
    # text (e.g. an API failure), fall back to the deterministic path so the
    # assistant still answers using real data instead of erroring out.
    if not all_tool_results and not final_text:
        fallback_step = NullProvider().next_step(SYSTEM_PROMPT, history, TOOL_SPECS, [])
        all_tool_results.extend(_run_tools(db, business_id, fallback_step.tool_calls))
        used_live_model = False

    if used_live_model and final_text:
        answer = final_text
        suggested_action = None
        reasoning = "Answer generated by the configured AI provider using only the tool results below."
    else:
        answer, suggested_action = _format_deterministic_answer(all_tool_results)
        reasoning = (
            "This answer was generated deterministically from real business-data tool "
            "calls (no external AI model is configured for this deployment, or it was "
            "unavailable)."
        )

    evidence_payload = {"tool_results": all_tool_results}

    db.add(
        AIMessage(
            conversation_id=conversation.id,
            role="assistant",
            content=answer,
            tool_calls={"calls": [r["tool"] for r in all_tool_results]},
            evidence=evidence_payload,
        )
    )
    db.add(
        AgentRun(
            business_id=business_id,
            agent_name="business_assistant",
            input_payload={"message": message},
            output_payload={"answer": answer, "tools_used": [r["tool"] for r in all_tool_results]},
            status="completed",
        )
    )
    db.flush()

    return {
        "conversation_id": conversation.id,
        "answer": answer,
        "evidence": evidence_payload,
        "reasoning": reasoning,
        "suggested_action": suggested_action,
        "used_live_model": used_live_model,
    }
